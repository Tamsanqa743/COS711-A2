class ValidationDiskDataset(Dataset):
    """Dataset for loading exported validation images directly from disk."""

    def __init__(self, val_dir="./validation_dataset/val_images", index_csv="./validation_dataset/val_images_index.csv"):
        self.val_dir = Path(val_dir)
        self.df = pd.read_csv(index_csv)

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]
        file_name = row["file_name"]
        img_path = self.val_dir / file_name

        if not img_path.exists():
            raise FileNotFoundError(f"Validation image not found: {img_path}")

        image = Image.open(img_path).convert("L")
        image = np.array(image, dtype=np.float32) / 255.0  # Normalize to 0.0 - 1.0
        image_tensor = torch.from_numpy(image).unsqueeze(0).float()

        return {
            "image": image_tensor,
            "file_name": file_name,
            "base_stem": row["base_stem"],
            "image_id": row["image_id"]
        }


def predict_validation_from_checkpoint(
    checkpoint_path="checkpoints/best_unet.pth",
    encoder_name="resnet34",
    pos_weight=5.0,
    val_dir="./validation_dataset/val_images",
    index_csv="./validation_dataset/val_images_index.csv",
    gt_csv="ground_truth.csv",
    output_pred_csv="./val_predictions.csv",
    threshold=0.35,
    min_area=10,
    batch_size=2
) -> tuple[pd.DataFrame, pd.DataFrame]:
    """
    Loads model weights from a .pth checkpoint, runs inference on validation
    images loaded from disk, generates instance RLEs, and returns (gt_df, pred_df).
    """
    device = "cuda" if torch.cuda.is_available() else "cpu"

    # 1. Instantiate Model Architecture & Load Weights from Checkpoint
    model = FilamentUNet(encoder_name=encoder_name, pos_weight=pos_weight)

    if not os.path.exists(checkpoint_path):
        raise FileNotFoundError(f"Checkpoint file not found: {checkpoint_path}")

    checkpoint = torch.load(checkpoint_path, map_location=device)
    if isinstance(checkpoint, dict) and "model_state_dict" in checkpoint:
        state_dict = checkpoint["model_state_dict"]
    elif isinstance(checkpoint, dict) and "state_dict" in checkpoint:
        state_dict = checkpoint["state_dict"]
    else:
        state_dict = checkpoint

    model.load_state_dict(state_dict)
    model.to(device)
    model.eval()
    print(f"Successfully loaded checkpoint '{checkpoint_path}' on {device}.")

    # 2. Instantiate DataLoader from Disk
    val_dataset = ValidationDiskDataset(val_dir=val_dir, index_csv=index_csv)
    val_loader = DataLoader(val_dataset, batch_size=batch_size, shuffle=False)

    # 3. Run Inference & Instance Segmentation
    records = []
    print(f"Generating predictions on {len(val_dataset)} validation images (threshold={threshold})...")

    with torch.no_grad():
        for batch in tqdm(val_loader, desc="Validation Inference"):
            images = batch["image"].to(device)
            base_stems = batch["base_stem"]

            with torch.amp.autocast('cuda', enabled=(device == "cuda"), dtype=torch.float16):
                logits = model(images)
                probs = torch.sigmoid(logits)

            for i in range(images.size(0)):
                base_stem = base_stems[i]
                prob_map = probs[i, 0].cpu().numpy()

                # Binarize probability map
                pred_mask = (prob_map > threshold).astype(np.uint8)

                # Extract connected component instances
                num_labels, labels, stats, _ = cv2.connectedComponentsWithStats(pred_mask, connectivity=8)

                filament_idx = 1
                for label in range(1, num_labels):
                    if stats[label, cv2.CC_STAT_AREA] < min_area:
                        continue  # Remove small noise artifacts

                    instance_mask = np.asfortranarray((labels == label).astype(np.uint8))
                    rle_dict = mask_utils.encode(instance_mask)
                    rle_str = rle_dict['counts'].decode('ascii')

                    records.append({
                        "filament_id": f"{base_stem}_{filament_idx}",
                        "segmentation_rle": rle_str
                    })
                    filament_idx += 1

    # 4. Save Predictions & Load Ground Truth CSV
    pred_df = pd.DataFrame(records)
    pred_df.to_csv(output_pred_csv, index=False)
    gt_df = pd.read_csv(gt_csv)

    print(f"\nExecution Summary:")
    print(f" - Predictions saved to: '{output_pred_csv}' ({len(pred_df)} instances)")
    print(f" - Ground truth loaded from: '{gt_csv}' ({len(gt_df)} image rows)")

    return gt_df, pred_df

