  # Optimiser and Scaler
  optimiser = optim.AdamW(model.parameters(),lr=lr, weight_decay=1e-2)
  scaler = torch.amp.GradScaler('cuda', enabled=(device=='cuda'))

  best_val_loss = float("inf")

  for epoch in range(1, epochs + 1):

    model.train()
    train_loss = 0.0
    optimiser.zero_grad(set_to_none=True)

    # for step, (images, masks) in enumerate (train_loader):
    #   images, masks = images.to(device, non_blocking=True), masks.to(device, non_blocking=True)
    for step, batch in enumerate(train_loader):
      images = batch["images"].to(device, non_blocking=True)
      masks = batch["masks"].to(device, non_blocking=True).float()

      # Ensure masks have shape (B, 1, H, W) for loss calculation
      if masks.ndim == 3:
          masks = masks.unsqueeze(1)

      with torch.amp.autocast('cuda', enabled=(device == "cuda"), dtype=torch.float16):
                logits = model(images)
                loss = model.compute_loss(logits, masks) / grad_accum_steps

      scaler.scale(loss).backward()

      if (step + 1) % grad_accum_steps == 0 or (step + 1) == len(train_loader):
                scaler.unscale_(optimiser)
                torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
                scaler.step(optimiser)
                scaler.update()
                optimiser.zero_grad(set_to_none=True)

      train_loss += loss.item() * grad_accum_steps

    model.eval()
    val_loss = 0.0
    with torch.no_grad():
        for batch in val_loader:
            images = batch["images"].to(device, non_blocking=True)
            masks = batch["masks"].to(device, non_blocking=True).float()

            if masks.ndim == 3:
                masks = masks.unsqueeze(1)

            with torch.amp.autocast('cuda', enabled=(device == "cuda"), dtype=torch.float16):
                logits = model(images)
                loss = model.compute_loss(logits, masks)

            val_loss += loss.item()

    avg_train = train_loss / len(train_loader)
    avg_val = val_loss / len(val_loader)
    print(f"Epoch [{epoch:02d}/{epochs:02d}] | Train Loss: {avg_train:.4f} | Val Loss: {avg_val:.4f}")

    # Save Best Checkpoint
    if avg_val < best_val_loss:
        best_val_loss = avg_val
        os.makedirs("checkpoints", exist_ok=True)
        checkpoint_path = "checkpoints/best_unet.pth"
        torch.save(model.state_dict(), checkpoint_path)
        print(f"  --> Saved checkpoint: {checkpoint_path} (Val Loss: {best_val_loss:.4f})")


