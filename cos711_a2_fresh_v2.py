def export_validation_dataset(
    val_dataset,
    train_image_dir: str,
    output_dir: str = "./validation_dataset"
) -> pd.DataFrame:
    """
    Copies the validation images into their own folder and saves an index of them.

    Args:
        val_dataset: PyTorch Subset dataset for validation.
        train_image_dir: Folder containing raw training images.
        output_dir: Directory where validation files will be exported.

    Returns:
        pd.DataFrame: val_index_df
    """
    output_path = Path(output_dir)
    val_images_dir = output_path / "val_images"
    val_images_dir.mkdir(parents=True, exist_ok=True)
    train_path = Path(train_image_dir)

    val_records = []

    for item in val_dataset:
        file_name = item["file_name"]
        image_id = item.get("image_id", Path(file_name).stem)
        base_stem = Path(file_name).stem

        val_records.append({
            "image_id": image_id,
            "file_name": file_name,
            "base_stem": base_stem,
            "num_filaments": item.get("num_filaments", 0)
        })

        # Copy physical image file to dedicated folder
        src_path = train_path / file_name
        dst_path = val_images_dir / file_name
        if src_path.exists():
            shutil.copy(src_path, dst_path)

    # Save validation image index
    val_index_df = pd.DataFrame(val_records)
    val_index_csv = output_path / "val_images_index.csv"
    val_index_df.to_csv(val_index_csv, index=False)

    print(f"Validation dataset exported to '{output_dir}':")
    print(f" - Physical images copied: {len(list(val_images_dir.glob('*')))}")
    print(f" - Image index saved: '{val_index_csv}'")

    return val_index_df

