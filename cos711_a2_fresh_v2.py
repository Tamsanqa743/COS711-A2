def extract_annotations_to_csv(annotations_file: str,
                               output_csv: str = 'annotations.csv',
                               output_ground_truth: str = 'ground_truth.csv'):
    """
    Extract annotations from a COCO JSON file to two CSVs, one row per annotation.
    An image_id repeats once for every filament annotated in that image.

    1. annotations.csv: image_id, segmentation_polygons (for training)
       segmentation_polygons is a JSON list of floats [x0, y0, x1, y1, ...]
    2. ground_truth.csv: image_id, segmentation_rle (for evaluation)
       RLE of that single filament, encoded with pycocotools
       (compressed COCO RLE counts string).

    Image size is fixed at 2048 x 2048 pixels (H-Alpha observations).

    Args:
        annotations_file: Path to the annotations JSON file
        output_csv: Path to save annotations CSV
        output_ground_truth: Path to save ground truth RLE CSV

    Returns:
        Tuple of (annotations_df, ground_truth_df)
    """

    IMAGE_HEIGHT = 2048
    IMAGE_WIDTH = 2048

    with open(annotations_file, 'r') as f:
        coco_data = json.load(f)

    annotations_list = []
    ground_truth_list = []

    for ann in coco_data['annotations']:
        for polygon in ann.get('segmentation', []):
            if len(polygon) < 6:  # Need at least 3 points
                continue

            annotations_list.append({
                'filament_id': ann['image_id'],
                'segmentation_polygons': json.dumps(polygon)
            })

            # Polygon -> RLE
            rle = mask_utils.merge(
                mask_utils.frPyObjects([polygon], IMAGE_HEIGHT, IMAGE_WIDTH))

            ground_truth_list.append({
                'filament_id': ann['image_id'],
                'segmentation_rle': rle['counts'].decode('utf-8')
            })

    annotations_df = pd.DataFrame(annotations_list)
    ground_truth_df = pd.DataFrame(ground_truth_list)

    annotations_df.to_csv(output_csv, index=False)
    ground_truth_df.to_csv(output_ground_truth, index=False)

    return annotations_df, ground_truth_df

class SolarFilamentDataset(Dataset):
    def __init__(
        self,
        images_dir,
        annotations_csv,
        image_extension=".jpeg",
        transform=None
    ):
        """
        Dataset for binary solar filament segmentation using CSV annotations.

        CSV expected columns (one row per filament, image_id repeats):
            image_id                (also accepted under the name filament_id)
            segmentation_polygons   (JSON list of floats [x0, y0, x1, y1, ...])

        Rows are regrouped by image_id so each sample is one image with all
        of its filaments.

        Args:
            images_dir: Folder containing image files
            annotations_csv: CSV file containing segmentation annotations (one row per filament)
            image_extension: image file extension, e.g. ".jpeg" or ".jpg"
            transform: optional transform
        """

        self.images_dir = Path(images_dir)
        df = pd.read_csv(annotations_csv).rename(columns={'filament_id': 'image_id'})
        df['segmentation_polygons'] = df['segmentation_polygons'].apply(json.loads)
        self.df = (
            df.groupby('image_id', sort=False)['segmentation_polygons']
            .agg(list)
            .reset_index()
        )
        self.df['num_filaments'] = self.df['segmentation_polygons'].apply(len)
        self.image_extension = image_extension
        self.transform = transform

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        row = self.df.iloc[idx]

        image_id = row['image_id']
        segmentation_polygons = row['segmentation_polygons']

        # Derive actual image filename from image_id
        file_stem = image_id.split("-", 1)[1]
        file_name = file_stem + self.image_extension
        img_path = self.images_dir / file_name

        if not img_path.exists():
            raise FileNotFoundError(f"Image not found: {img_path}")

        # Load image as grayscale, scaled to 0.0 - 1.0 (same as ValidationDiskDataset)
        image = Image.open(img_path).convert("L")
        image = np.array(image, dtype=np.float32) / 255.0

        height, width = image.shape

        # Parse segmentation polygons
        polygons = self._parse_polygons(segmentation_polygons)

        # Create mask from polygons
        mask = self._create_mask_from_polygons(polygons, height, width)

        if self.transform:
            image = self.transform(image)

        image = torch.from_numpy(image).unsqueeze(0).float()
        mask = torch.from_numpy(mask).long()

        return {
            "image": image,           # shape: (1, H, W)
            "mask": mask,             # shape: (H, W) - binary (0 or 1)
            "image_id": image_id,
            "file_name": file_name,
            "num_filaments": row['num_filaments']
        }

    def _parse_polygons(self, segmentation_polygons):
      """
      Parse segmentation polygons for one image.

      Expected format: list of polygons (already grouped by image in __init__),
      or a JSON string of the same, e.g. "[[x0, y0, x1, y1, ...], [...]]"

      Returns:
          List of polygons, where each polygon is a list of floats
      """

      if isinstance(segmentation_polygons, list):
          return segmentation_polygons

      if pd.isna(segmentation_polygons):
          return []

      segmentation_polygons = str(segmentation_polygons).strip()

      try:
          # Parse JSON string
          polygons = json.loads(segmentation_polygons)
          return polygons
      except (ValueError, json.JSONDecodeError) as e:
          print(f"Warning: Could not parse polygons: {segmentation_polygons[:100]}")
          print(f"Error: {e}")
          return []

    def _create_mask_from_polygons(self, polygons, height, width):
        """
        Create binary segmentation mask from multiple polygons.

        Args:
            polygons: List of polygons, where each polygon is a list of floats
                     [x0, y0, x1, y1, ..., xn, yn]
            height: Image height
            width: Image width

        Returns:
            Binary mask (H, W) with 0=background, 1=filament
        """
        mask = np.zeros((height, width), dtype=np.uint8)

        for polygon_points in polygons:
            if len(polygon_points) < 6:  # Need at least 3 points
                continue

            coords = np.array(polygon_points).reshape(-1, 2).astype(np.int32)

            # Draw filled polygon
            cv2.fillPoly(mask, [coords], color=1)

        return mask

def create_data_loaders(
    images_dir: str,
    annotations_csv: str,
    batch_size: int = 4,
    num_workers: int = 0,
    val_split: float = 0.2,
    random_state: int = 42,
    image_extension: str = ".jpeg"
):
    """
    Create train and validation DataLoaders from the annotations CSV.

    The CSV (written by extract_annotations_to_csv) has one row per filament.
    SolarFilamentDataset regroups those rows by image_id, so each sample is one
    image_id with all of its filaments.

    The same image can appear under several image_ids (e.g. 010101-20110203082634Lh
    and 010102-20110203082634Lh: the prefix is the annotator, the suffix is the
    image name). The split is therefore done on the image-name suffix so that all
    image_ids sharing a suffix land in the same set.

    Args:
        images_dir: Path to images folder
        annotations_csv: Path to annotations.csv (columns: image_id, segmentation_polygons)
        batch_size: Batch size for training
        num_workers: Number of DataLoader workers (0 for Colab)
        val_split: Approximate fraction of samples for validation (default 0.2 = 20%).
                   Whole suffix groups are moved at a time, so it can overshoot slightly.
        random_state: Random seed for reproducibility
        image_extension: Image file extension (e.g., ".jpeg", ".jpg")

    Returns:
        train_loader: DataLoader for training
        val_loader: DataLoader for validation
        train_dataset: Training dataset
        val_dataset: Validation dataset
    """
    # Create full dataset from CSV (one sample per image_id)
    print(f"\nCreating dataset from CSV: {annotations_csv}")
    full_dataset = SolarFilamentDataset(
        images_dir=images_dir,
        annotations_csv=annotations_csv,
        image_extension=image_extension
    )

    total_size = len(full_dataset)

    # Group dataset positions by image-name suffix ("<annotator>-<image name>")
    suffixes = full_dataset.df['image_id'].str.split('-', n=1).str[1]
    groups = suffixes.groupby(suffixes).indices   # {suffix: positions in dataset}

    # Shuffle the groups, then fill the validation set group by group
    group_keys = sorted(groups)
    np.random.RandomState(random_state).shuffle(group_keys)

    target_val_size = int(total_size * val_split)
    val_indices = []
    for key in group_keys:
        if len(val_indices) >= target_val_size:
            break
        val_indices.extend(groups[key].tolist())

    val_set = set(val_indices)
    train_indices = [i for i in range(total_size) if i not in val_set]

    train_dataset = Subset(full_dataset, train_indices)
    val_dataset = Subset(full_dataset, val_indices)

    print(f"{total_size} image_ids, {full_dataset.df['num_filaments'].sum()} filaments, "
          f"{len(groups)} distinct images -> "
          f"{len(train_indices)} train / {len(val_indices)} val image_ids")


    def collate_fn(batch):
        """Collate function for DataLoader"""
        images = torch.stack([item["image"] for item in batch])
        masks = torch.stack([item["mask"] for item in batch])
        image_ids = [item["image_id"] for item in batch]
        file_names = [item["file_name"] for item in batch]
        num_filaments = [item["num_filaments"] for item in batch]

        return {
            "images": images,           # (batch, 1, H, W)
            "masks": masks,             # (batch, H, W)
            "image_ids": image_ids,
            "file_names": file_names,
            "num_filaments": num_filaments
        }

    train_loader = DataLoader(
        train_dataset,
        batch_size=batch_size,
        shuffle=True,
        num_workers=num_workers,
        collate_fn=collate_fn,
        pin_memory=True
    )

    val_loader = DataLoader(
        val_dataset,
        batch_size=batch_size,
        shuffle=False,
        num_workers=num_workers,
        collate_fn=collate_fn,
        pin_memory=True
    )

    return train_loader, val_loader, train_dataset, val_dataset

